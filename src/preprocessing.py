"""
preprocessing.py
----------------
Cleans raw electricity market data and engineers domain-specific features:
- Missing value imputation (time-based interpolation)
- Heating & Cooling Degree Days (HDD / CDD)
- Renewable penetration share
- Calendar & seasonal indicators
- Leakage-free autoregressive lags and rolling volatility measures
"""

from pathlib import Path
import numpy as np
import pandas as pd


def clean_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Sort chronologically, enforce data types, and impute missing values.

    Parameters
    ----------
    df : pd.DataFrame
        Raw electricity market dataset.

    Returns
    -------
    pd.DataFrame
        Cleaned dataset with no missing values.
    """
    df = df.copy()
    df["date"] = pd.to_datetime(df["date"])
    df = df.sort_values("date").drop_duplicates(subset=["date"]).reset_index(drop=True)

    # Set date as index temporarily for accurate time-based interpolation
    df = df.set_index("date")
    numeric_cols = df.select_dtypes(include=[np.number]).columns
    df[numeric_cols] = df[numeric_cols].interpolate(method="time").bfill().ffill()
    df = df.reset_index()

    return df


def engineer_features(
    df: pd.DataFrame,
    hdd_base: float = 18.0,
    cdd_base: float = 22.0,
) -> pd.DataFrame:
    """
    Construct domain-specific energy economics and time-series features.

    Parameters
    ----------
    df : pd.DataFrame
        Cleaned daily electricity market dataset.
    hdd_base : float
        Base temperature (°C) for Heating Degree Days.
    cdd_base : float
        Base temperature (°C) for Cooling Degree Days.

    Returns
    -------
    pd.DataFrame
        Feature-engineered dataset ready for EDA and modeling.
    """
    df = df.copy()

    # 1. Weather Extremes: Heating & Cooling Degree Days
    df["hdd"] = np.maximum(0.0, hdd_base - df["temperature_c"])
    df["cdd"] = np.maximum(0.0, df["temperature_c"] - cdd_base)

    # 2. Energy Market Fundamentals
    df["renewable_share"] = df["renewable_gen_mwh"] / df["demand_mwh"]
    df["net_load_mwh"] = df["demand_mwh"] - df["renewable_gen_mwh"]

    # 3. Calendar & Seasonality Features
    df["day_of_week"] = df["date"].dt.dayofweek
    df["month"] = df["date"].dt.month
    df["is_weekend"] = (df["day_of_week"] >= 5).astype(int)
    df["is_winter"] = df["month"].isin([12, 1, 2]).astype(int)
    df["is_summer"] = df["month"].isin([6, 7, 8]).astype(int)

    # 4. Autoregressive Lag Features (strictly past values)
    df["price_lag_1"] = df["electricity_price"].shift(1)
    df["price_lag_7"] = df["electricity_price"].shift(7)
    df["price_lag_14"] = df["electricity_price"].shift(14)
    df["demand_lag_1"] = df["demand_mwh"].shift(1)
    df["gas_price_lag_1"] = df["gas_price"].shift(1)

    # 5. Rolling Statistics & Volatility Clustering (shifted by 1 to prevent leakage)
    shifted_price = df["electricity_price"].shift(1)
    df["price_rolling_mean_7"] = shifted_price.rolling(window=7).mean()
    df["price_rolling_std_7"] = shifted_price.rolling(window=7).std()
    df["price_rolling_std_30"] = shifted_price.rolling(window=30).std()

    # Daily percentage price change (for volatility visualization in EDA)
    df["price_return_pct"] = df["electricity_price"].pct_change() * 100.0

    # Drop initial rows with NaNs generated by lag and rolling windows
    initial_rows = len(df)
    df = df.dropna().reset_index(drop=True)
    dropped_rows = initial_rows - len(df)
    print(f"[preprocessing] Dropped {dropped_rows} initial rows due to lag/rolling windows.")

    return df


def run_preprocessing(
    raw_path: str = "data/raw/electricity_market_data.csv",
    processed_path: str = "data/processed/electricity_market_processed.csv",
) -> pd.DataFrame:
    """
    Execute the full preprocessing pipeline from raw CSV to processed CSV.
    """
    raw_file = Path(raw_path)
    if not raw_file.exists():
        raise FileNotFoundError(
            f"Raw data file not found at {raw_file}. Run src/data_generator.py first."
        )

    df_raw = pd.read_csv(raw_file)
    df_clean = clean_data(df_raw)
    df_processed = engineer_features(df_clean)

    output_file = Path(processed_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    df_processed.to_csv(output_file, index=False)
    print(
        f"[preprocessing] Processed dataset saved to {output_file} "
        f"({len(df_processed)} rows, {df_processed.shape[1]} columns)."
    )

    return df_processed


if __name__ == "__main__":
    run_preprocessing()
